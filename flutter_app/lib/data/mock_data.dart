// Helper functions
Anime? getAnimeById(int id) {
  try { return allAnime.firstWhere((a) => a.id == id); } catch (_) { return null; }
}

List<Episode> getEpisodesForAnime(int id) {
  final anime = getAnimeById(id);
  if (anime == null) return [];
  final count = anime.episodes > 30 ? 30 : anime.episodes;
  return List.generate(count, (i) {
    final epNum = i + 1;
    final watched = anime.watchedEpisodes >= epNum;
    return Episode(
      number: epNum,
      title: 'Episode $epNum',
      description: 'The adventure continues in episode $epNum of ${anime.title}. New challenges await our heroes.',
      releaseDate: '2024-${(i % 12 + 1).toString().padLeft(2, '0')}-15',
      subAvailable: true,
      dubAvailable: i % 3 == 0,
      thumbColors: anime.coverColors,
      thumbLetter: anime.letter,
      watched: watched,
    );
  });
}
